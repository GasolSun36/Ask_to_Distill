"""verl agent loop that rolls out one tau2-bench episode for OPD.

Agent-specific OPD is the SAME OPD objective as math and code -- top-16
student support, reverse KL weighted by the renormalised student
probabilities, ``token_reward_direct`` advantages, the same lr and precision
(configs/base/opd.yaml) -- applied to a masked multi-turn trajectory. This
module builds that trajectory; it does not change the loss.

1. Multi-turn masked distillation. An episode interleaves policy tokens (the
   student's replies and tool calls), tool outputs and simulated-user turns in
   one token sequence. Only tokens the policy generated carry
   ``response_mask = 1``; tool results and user-simulator text are context with
   mask 0. verl multiplies both the OPD token advantage and the actor loss by
   ``response_mask``, and the ``token-mean`` normaliser counts policy tokens
   only::

       L = (1 / sum_t m_t) * sum_t m_t * l_t^OPD,   m_t = 1[token t generated by the student]

   so observation tokens -- JSON the environment wrote, text the simulated user
   wrote -- condition both models but never count as teacher/student
   disagreement: they are not actions of the student.
2. Stop-on-repeat (``TAU2_STOP_ON_REPEAT=1``). When the student's user-facing
   reply near-duplicates its previous one (``difflib`` ratio >=
   ``TAU2_REPEAT_SIM`` on the first 600 characters), that turn is removed from
   the sequence and the mask and the episode ends, so a small model's
   degenerate repetition loop (the same sign-off every turn while the simulator
   keeps thanking it) never reaches the loss.
3. Budgets. One ``response_length`` budget (8,192 tokens in the final runs) is
   shared by all turns, policy and observation tokens alike, and an episode has
   at most ``TAU2_MAX_TURNS`` (20) assistant turns; whichever runs out first
   ends it. Tool output is cut
   to ``TAU2_MAX_TOOL_CHARS`` characters.

The environment lives behind ``envside.env_service`` (/env/new, /env/call): this
runs inside verl in the a2d env, which cannot import tau2. The user simulator is
a separate frozen OpenAI-compatible endpoint (Qwen3-4B-Instruct-2507,
temperature 1.0, at most 512 tokens per turn), never the policy. A scripted
greeting and the simulator's first message are part of the prompt, so the first
scored token answers a real request.

Observation tokens are rendered the way verl's own ToolAgentLoop does it: only
the newly added messages go through the chat template (with the generation
prompt), and the template's system prefix is stripped, so the running token
sequence is extended rather than re-rendered.

Dataset rows carry the episode in extra_info: {"domain": ..., "scenario": {...}}.

Settings are read from the environment at import, as verl imports this module
inside each AgentLoopWorker; ``tau2.trainside.opd_launch`` delivers them to every
worker through ``ray_kwargs.ray_init.runtime_env.env_vars`` (rendered by
``ask2distill.tau2.env`` for the role ``opd``, plus the service and simulator
URLs). The two paths (``TAU2_CTX``, ``TAU2_USER_GUIDELINES``) have no default and
are checked when the class initialises.

Quirk kept as run: ``/env/close`` is posted with ``{"domain": sid}`` (the service
reuses its /env/new body model for close).

See docs/TAU2.md, "Agent-specific OPD".
"""
import asyncio
import json
import logging
import os
import random
import uuid
from typing import Any

import aiohttp

from verl.experimental.agent_loop.agent_loop import AgentLoopBase, AgentLoopOutput, register
from verl.experimental.agent_loop.tool_parser import ToolParser
from verl.utils.profiler import simple_timer

logger = logging.getLogger(__file__)

TAU2_CTX = os.environ.get("TAU2_CTX", "")
SVC = os.environ.get("TAU2_SVC", "http://127.0.0.1:8710")
USER_MODEL = os.environ.get("TAU2_USER_MODEL", "Qwen3-4B-Instruct-2507")
USER_BASES = [b for b in os.environ.get("TAU2_USER_BASE", "").split(",") if b]
# Optional: a file a supervising job rewrites with the currently READY simulator
# endpoints (comma list). Serve jobs hit their 4h wall on a different clock from
# training; on a failed call the loop re-reads this file instead of dying.
USER_BASE_FILE = os.environ.get("TAU2_USER_BASE_FILE", "")
USER_RETRY_S = int(os.environ.get("TAU2_USER_RETRY_S", 1800))
USER_GUIDELINES = os.environ.get("TAU2_USER_GUIDELINES", "")
MAX_ASSISTANT_TURNS = int(os.environ.get("TAU2_MAX_TURNS", 10))
MAX_TOOL_CHARS = int(os.environ.get("TAU2_MAX_TOOL_CHARS", 2000))
GREETING = "Hi! How can I help you today?"
STOP_TOKENS = ("###STOP###", "###TRANSFER###", "###OUT-OF-SCOPE###")
# Stop-on-repeat. Opt-in at the module level (default off, so runs started
# without it are unchanged on resume); on in every final OPD arm. End the
# episode when the policy's user-facing reply near-duplicates its previous one.
# An earlier OPD run learned a closing loop -- the same sign-off every turn while
# the simulator keeps thanking and never sends ###STOP### -- which filled the
# turn and token budget and kept feeding those tokens to the loss. The repeated
# turn itself is dropped, so it is neither scored nor kept as context.
STOP_ON_REPEAT = os.environ.get("TAU2_STOP_ON_REPEAT", "0") == "1"
REPEAT_SIM = float(os.environ.get("TAU2_REPEAT_SIM", 0.9))


def _near_dup(a, b):
    import difflib
    a, b = " ".join(a.split()).lower(), " ".join(b.split()).lower()
    if not a or not b:
        return False
    return a == b or difflib.SequenceMatcher(None, a[:600], b[:600]).ratio() >= REPEAT_SIM


@register("tau2_agent")
class Tau2AgentLoop(AgentLoopBase):
    """One tau2 episode per dataset row; policy tokens mask 1, observations mask 0."""

    @classmethod
    def init_class(cls, config, tokenizer, processor, **kwargs):
        if cls._class_initialized:
            return
        missing = [n for n, v in (("TAU2_CTX", TAU2_CTX), ("TAU2_USER_GUIDELINES", USER_GUIDELINES)) if not v]
        if missing:
            raise RuntimeError(f"tau2 agent loop: {', '.join(missing)} not set (delivered through "
                               "runtime_env by ask2distill.tau2.trainside.opd_launch)")
        cls._class_initialized = True
        cls.tokenizer = tokenizer
        cls.ctx = json.load(open(TAU2_CTX))
        cls.user_guidelines = open(USER_GUIDELINES).read()
        cls.response_length = config.actor_rollout_ref.rollout.response_length
        cls.tool_parser = ToolParser.get_tool_parser(
            config.actor_rollout_ref.rollout.multi_turn.format, tokenizer)
        cls.apply_chat_template_kwargs = dict(config.data.get("apply_chat_template_kwargs", {}) or {})
        cls.system_prefix = tokenizer.apply_chat_template(
            [{}], add_generation_prompt=False, tokenize=True, **cls.apply_chat_template_kwargs)
        cls.user_bases = None
        cls._set_user_bases(USER_BASES or cls._read_user_file())

    @classmethod
    def _read_user_file(cls):
        try:
            return [b for b in open(USER_BASE_FILE).read().strip().split(",") if b]
        except Exception:
            return []

    @classmethod
    def _set_user_bases(cls, bases):
        from openai import AsyncOpenAI
        if bases and bases != cls.user_bases:
            cls.user_bases = bases
            cls.user_clients = [AsyncOpenAI(api_key="EMPTY", base_url=b, timeout=300) for b in bases]

    # ---- environment + simulator ---------------------------------------------
    async def _post(self, path, body):
        async with aiohttp.ClientSession() as s:
            async with s.post(f"{SVC}{path}", json=body, timeout=aiohttp.ClientTimeout(total=300)) as r:
                return await r.json()

    async def _user_turn(self, scenario, dialogue):
        """One simulator reply. Roles flipped: the agent is the simulator's 'user'."""
        sysmsg = f"{self.user_guidelines}\n\n<scenario>\n{json.dumps(scenario, ensure_ascii=False)}\n</scenario>"
        flipped = [{"role": "user" if m["role"] == "assistant" else "assistant", "content": m["content"] or ""}
                   for m in dialogue]
        msgs = [{"role": "system", "content": sysmsg}] + flipped
        waited = 0
        while True:
            try:
                r = await random.choice(self.user_clients).chat.completions.create(
                    model=USER_MODEL, messages=msgs, max_tokens=512, temperature=1.0)
                return (r.choices[0].message.content or "").strip()
            except Exception as e:
                if not USER_BASE_FILE or waited >= USER_RETRY_S:
                    raise
                logger.warning(f"user simulator call failed ({e!r}); re-reading {USER_BASE_FILE}")
                await asyncio.sleep(20)
                waited += 20
                type(self)._set_user_bases(self._read_user_file())

    async def _render(self, messages, tools=None):
        """Token ids of `messages` as a continuation (system prefix stripped)."""
        ids = await self.loop.run_in_executor(None, lambda: self.tokenizer.apply_chat_template(
            messages, tools=tools, add_generation_prompt=True, tokenize=True, **self.apply_chat_template_kwargs))
        return ids[len(self.system_prefix):]

    # ---- episode ---------------------------------------------------------------
    async def run(self, sampling_params: dict[str, Any], **kwargs) -> AgentLoopOutput:
        ei = kwargs.get("extra_info") or {}
        domain = ei["domain"]
        scenario = ei["scenario"]
        if isinstance(scenario, str):
            scenario = json.loads(scenario)
        metrics, request_id = {}, uuid.uuid4().hex
        system, tools = self.ctx[domain]["system"], self.ctx[domain]["tools"]
        sid = (await self._post("/env/new", {"domain": domain}))["sid"]

        # Scripted greeting, then the simulator opens: the first scored token is
        # the policy's answer to a real request, not a canned hello.
        dialogue = [{"role": "assistant", "content": GREETING}]
        first = await self._user_turn(scenario, dialogue)
        dialogue.append({"role": "user", "content": first})
        prompt_msgs = [{"role": "system", "content": system}] + dialogue
        prompt_ids = await self.loop.run_in_executor(None, lambda: self.tokenizer.apply_chat_template(
            prompt_msgs, tools=tools, add_generation_prompt=True, tokenize=True, **self.apply_chat_template_kwargs))
        n_prompt = len(prompt_ids)
        ids = list(prompt_ids)
        mask: list[int] = []
        turns = 0
        last_reply = None
        metrics_repeat = 0
        try:
            while turns < MAX_ASSISTANT_TURNS and len(mask) < self.response_length:
                with simple_timer("generate_sequences", metrics):
                    out = await self.server_manager.generate(
                        request_id=request_id, prompt_ids=ids, sampling_params=sampling_params)
                gen = list(out.token_ids)
                n_before = len(ids)
                ids += gen
                mask += [1] * len(gen)                       # policy tokens: scored
                turns += 1
                if len(mask) >= self.response_length:
                    break
                content, calls = await self.tool_parser.extract_tool_calls(gen)
                if calls:
                    obs = []
                    for c in calls:
                        try:
                            args = json.loads(c.arguments) if isinstance(c.arguments, str) else (c.arguments or {})
                        except Exception:
                            args = {}
                        r = await self._post("/env/call", {"sid": sid, "name": c.name, "args": args})
                        obs.append({"role": "tool", "content": str(r.get("out", r.get("error", "")))[:MAX_TOOL_CHARS]})
                    new = obs
                else:
                    if STOP_ON_REPEAT and last_reply is not None and _near_dup(content or "", last_reply):
                        del ids[n_before:]
                        del mask[len(mask) - len(gen):]
                        turns -= 1
                        metrics_repeat = 1
                        break
                    last_reply = content or ""
                    dialogue.append({"role": "assistant", "content": content})
                    reply = await self._user_turn(scenario, dialogue)
                    if any(s in reply for s in STOP_TOKENS):
                        break
                    dialogue.append({"role": "user", "content": reply})
                    new = [{"role": "user", "content": reply}]
                obs_ids = await self._render(new)
                if len(mask) + len(obs_ids) >= self.response_length:
                    break
                ids += obs_ids
                mask += [0] * len(obs_ids)                   # observation: never scored
        finally:
            try:
                await self._post("/env/close", {"domain": sid})
            except Exception:
                pass

        mask = mask[: self.response_length]
        return AgentLoopOutput(
            prompt_ids=ids[:n_prompt],
            response_ids=ids[n_prompt:][: len(mask)],
            response_mask=mask,
            num_turns=turns,
            metrics=metrics,
            extra_fields={"domain": domain, "assistant_turns": turns,
                          **({"stopped_on_repeat": metrics_repeat} if STOP_ON_REPEAT else {})},
        )

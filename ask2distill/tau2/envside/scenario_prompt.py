"""Build the synthesizer's prompt: real database entities in, a scenario + gold actions out.

The synthesizer writes two coupled things, not one. The scenario card is what the
user simulator plays; the action list is what the environment executes to derive
the gold database hash. They have to describe the same task, because the reward
is "the student failed to reach the state those actions produce".

Entities are sampled from the live database rather than invented. This is the
counterpart of topic conditioning in the math and code versions, and it is what makes the
validity gate passable at all: a card citing order #W9999999 produces an action
list that throws, and the environment rejects it (measured: ValueError "Order not
found"). Handing the model real ids up front means the gate filters careless
scenarios, not hallucinated ones.

The instruction also demands that every value the actions need be stated by the
customer: an earlier synthesizer's first step showed 80% of grounded cards failing the teacher gate as
under-specified ("add additional baggage" against total_baggages=5). Telling the
synthesizer the rule is the same fix as listing the tool names was for the 0% yield.

The instruction demands at least one write action because a read-only scenario
leaves the gold hash equal to the initial hash, and the reward -- a hash
comparison -- cannot separate anything. That was measured on the real tasks:
26 of 278 have read-only criteria and all 26 leave the database untouched.

Notes:
  * the DB directory comes from A2D_TAU2_DB_DIR and TAU2_CTX is required;
  * `DETERMINISTIC` (off by default) sorts the product-id set in `_retail`.
"""
import functools
import json
import os
import random

from ask2distill.tau2.envside import settings

CTX = json.load(open(settings.require("TAU2_CTX")))

# Directory of <domain>/db.json. Read from its own variable, A2D_TAU2_DB_DIR
# (a shared TAU2_DATA name collided with the training job's prompt-parquet
# variable); default is the fork's data dir, which every final run read.
DATA = settings.db_dir()

# `_retail` iterates a set of product ids, whose order follows per-process string
# hashing, so the released GENRL_TAU2_V6/V7 retail rows cannot be regenerated byte
# for byte (the released parquets are canonical). build_prompts switches this on
# (and pins PYTHONHASHSEED); it stays off everywhere else, as in the final runs.
DETERMINISTIC = False

INSTRUCTION = """You are designing evaluation scenarios for a customer-service agent operating in the {domain} domain.

These are the ONLY tools that exist. Any other name fails and the scenario is
discarded -- do not invent tools, and do not guess a name from a pattern.

<tools>
{tools}
</tools>

Below are REAL records from the live database. Every id you use must come from these records.

<records>
{records}
</records>

Key domain rules the action list must respect (a violating action fails and the
scenario is discarded):
{rules}

Write ONE scenario a customer could plausibly call about, together with the exact
sequence of tool calls that correctly resolves it.

Requirements:
- The customer's goal must require changing the database: at least one action from
  the tool list above that is not a lookup.
- Make it take several dependent steps, not a single call. The agent should have to
  look something up before it can act.
- Choose the scenario from _possible_scenarios in the records: a return or exchange
  ONLY for an order listed under return_or_exchange, a cancellation or modification
  ONLY for one under cancel_or_modify. Anything else fails and is discarded.
- Fully specify the request. Every value the agent will have to enter must be
  stated by the customer, in the customer's own words, in reason_for_call or
  known_info: exact quantities ("add 2 checked bags", never "additional baggage"),
  which item or variant (name the option: color, size, model), which payment
  method ("pay with my PayPal"), the complete new address. If the customer would
  not know a value, they must give a rule the agent can apply after looking it up
  ("the cheapest available one"). A request that does not pin down exactly one
  action list is invalid and will be discarded.
- known_info MUST let the agent identify the customer: give the email, or the full
  name AND zip code, or the order / reservation id -- and any date or flight the
  request refers to. A card that omits how the agent can look the customer up is
  discarded.
- known_info: what the customer can state. unknown_info: what they cannot recall,
  forcing the agent to look it up another way. Leave unknown_info null if nothing fits.
- The action list must be complete and executable in order, with exact ids and
  arguments from the records above.

Output ONLY this JSON, no commentary:
{{"scenario": {{"reason_for_call": "...", "known_info": "...", "unknown_info": null,
  "task_instructions": "..."}},
  "actions": [{{"name": "tool_name", "arguments": {{}}}}]}}"""


def _retail(db, rng):
    users = db["users"]
    # Prefer a customer who has BOTH a delivered and a pending order, so every
    # scenario family is possible for the records shown. Only 63% of sampled
    # prompts contained a delivered order, and the untrained synthesizer defaults
    # to returns: 22% of a step's cards died on "Non-delivered order cannot be
    # returned" even with the per-order allowed list present.
    best = None
    for _ in range(200):
        u = users[rng.choice(list(users))]
        oids = [o for o in u.get("orders", []) if o in db["orders"]]
        if not oids:
            continue
        sts = {db["orders"][o].get("status") for o in oids}
        if "delivered" in sts and "pending" in sts:
            best = (u, oids); break
        best = best or (u, oids)
    if best is None:
        return None
    u, oids = best
    # show delivered/pending first so both families are within the first 3
    oids = sorted(oids, key=lambda o: {"delivered": 0, "pending": 1}.get(db["orders"][o].get("status"), 2))
    orders = [dict(db["orders"][o]) for o in oids[:3]]
    # Which write actions each order's status permits, spelled out on the record
    # itself. The policy digest already said "returns only on delivered orders",
    # and the synthesizer still lost 14% of a step's cards to "Non-delivered order
    # cannot be returned": a rule in the instructions is not read against the
    # status field, a per-record list is.
    def allowed(st):
        return (["cancel_pending_order", "modify_pending_order_address",
                 "modify_pending_order_items", "modify_pending_order_payment"] if st == "pending"
                else ["return_delivered_order_items", "exchange_delivered_order_items"] if st == "delivered"
                else [])
    # allowed list as the FIRST key of each order: appended at the end of a long
    # record it was ignored
    orders = [{"_allowed_write_actions": allowed(o.get("status")), **o} for o in orders]
    for o in orders:
        o["_order_total"] = round(sum(i.get("price", 0) for i in o.get("items", [])), 2)
        for it in o.get("items", []):
            var = db["products"].get(it["product_id"], {}).get("variants", {})
            it["_swap_to_item_ids"] = [v for v, d in var.items()
                                       if v != it["item_id"] and d.get("available")][:4]
    possible = {"return_or_exchange": [o["order_id"] for o in orders if o.get("status") == "delivered"],
                "cancel_or_modify": [o["order_id"] for o in orders if o.get("status") == "pending"]}
    ordered = {i["item_id"] for o in orders for i in o.get("items", [])}
    pids = {i["product_id"] for o in orders for i in o.get("items", [])}
    # Full product records carry every variant -- dozens of item_ids with option
    # dicts -- and pushed retail prompts to a 6.5k-token median, 43% of rows past
    # the 4096 cap. The synthesizer needs the ordered variants plus a few available
    # siblings to write an exchange or modification; nothing else.
    prods = {}
    for pid in (sorted(pids) if DETERMINISTIC else list(pids))[:4]:
        if pid not in db["products"]:
            continue
        prod = db["products"][pid]
        var = prod.get("variants", {})
        keep = [v for v in var if v in ordered]
        keep += [v for v in var if v not in ordered and var[v].get("available")][: max(0, 6 - len(keep))]
        prods[pid] = {"name": prod.get("name"), "product_id": pid,
                      "variants": {v: var[v] for v in keep}}
    balances = {k: v.get("balance") for k, v in (u.get("payment_methods") or {}).items() if "balance" in v}
    return {"_possible_scenarios": possible, "_gift_card_balances": balances,
            "user": u, "orders": orders, "products": prods}


def _airline(db, rng):
    users = db["users"]
    for _ in range(50):
        u = users[rng.choice(list(users))]
        rids = [r for r in u.get("reservations", []) if r in db["reservations"]]
        if rids:
            break
    else:
        return None
    res = [dict(db["reservations"][r]) for r in rids[:3]]
    for r in res:
        r["_can_update_flights"] = r.get("cabin") != "basic_economy"
        r["_n_passengers"] = len(r.get("passengers", []))
        r["_note"] = "free checked bags per passenger depend on the user's membership tier and this cabin; nonfree_baggages = total - free allowance"
    # Bookable flights on the same routes. Without them every flight change or
    # booking cited an invented flight number and failed, which is why an earlier
    # synthesizer's airline cards collapsed onto baggage updates -- the one airline write that
    # needs no flight data.
    routes = {(leg["origin"], leg["destination"]) for r in res for leg in r.get("flights", [])}
    cand = []
    for f in db["flights"].values():
        if (f["origin"], f["destination"]) not in routes:
            continue
        for dt, d in f["dates"].items():
            if d.get("status") == "available":
                cand.append({"flight_number": f["flight_number"], "origin": f["origin"],
                             "destination": f["destination"], "date": dt,
                             "prices": d.get("prices"), "available_seats": d.get("available_seats")})
    rng.shuffle(cand)
    return {"user": u, "reservations": res, "bookable_flights": cand[:8]}


SAMPLERS = {"retail": _retail, "airline": _airline}

# Target write action per prompt row (v4). An earlier synthesizer drifted to three task types --
# baggage updates, exchanges, returns -- and embedding diversity never saw it.
# Fixing the type up front and letting RL work on difficulty WITHIN the type is
# the same move as topic conditioning in the math and code versions.
TARGETS = {
    "retail": ["cancel_pending_order", "modify_pending_order_address", "modify_pending_order_items",
               "modify_pending_order_payment", "modify_user_address",
               "return_delivered_order_items", "exchange_delivered_order_items"],
    "airline": ["update_reservation_flights", "update_reservation_baggages",
                "update_reservation_passengers", "cancel_reservation", "book_reservation"],
}

# Compact digests of the policy rules that decide whether an action can execute
# at all. Step 1 of an earlier synthesizer lost 18% of cards to exactly these: returning an order that
# is not delivered, exchanging a pending order, paying for baggage with a
# certificate. The synthesizer sees each record's status field; it needs to know
# which statuses each write action requires.
RULES = {
    "retail": """- cancel_pending_order / modify_pending_order_* only on orders with status "pending".
- return_delivered_order_items / exchange_delivered_order_items only on status "delivered".
- Exchanges and item modifications swap a variant for another variant of the SAME product (same product_id), and the new variant must have available: true.
- Price differences are charged/refunded to one of the customer's own payment methods; a gift card must have enough balance.
- Only ONE modify_pending_order_items call is allowed per order (it moves the order out of pending).
- cancel_pending_order: reason must be exactly "no longer needed" or "ordered by mistake".
- modify_pending_order_payment: the new payment method must differ from the one the order was paid with.
- Address changes: the customer states the complete new address (address1, address2, city, state, country, zip) word for word in known_info.""",
    "airline": """- Baggage: checked-bag allowance depends on membership (regular/silver/gold) and cabin; nonfree_baggages = total_baggages minus the free allowance, each nonfree bag is $50, and total_baggages is the FINAL total on the reservation, not the number added.
- Baggage and flight changes are paid with the customer's own gift card or credit card -- a certificate cannot pay for a baggage update.
- Basic economy flights cannot be modified; cancellations follow the 24-hour / insurance / airline-cancelled rules.
- update_reservation_flights keeps the same origin/destination and trip type; new flights must be taken from bookable_flights.
- update_reservation_passengers: pass the FULL passenger list with the same number of passengers as the reservation; only names/dates of birth change, and the customer states each new value.""",
}


@functools.lru_cache(maxsize=4)
def _load_db(domain: str):
    """Cached: retail's db.json is 2.8MB and airline's 7MB, and building a few
    thousand prompt rows would otherwise re-read them once per row."""
    return json.load(open(os.path.join(DATA, domain, "db.json")))


def tool_list(domain: str) -> str:
    """Compact signatures for every tool in the domain.

    The first yield test scored 0%: 58 of 60 action lists named tools that do not
    exist (update_payment_method, find_order, cancel_order), because the prompt
    described the READ-tool naming pattern but never listed the actual tools. The
    model was left guessing names from a pattern.
    """
    out = []
    for t in CTX[domain]["tools"]:
        fn = t.get("function", t)
        params = (fn.get("parameters") or {}).get("properties") or {}
        req = set((fn.get("parameters") or {}).get("required") or [])
        sig = ", ".join(f"{k}{'' if k in req else '?'}" for k in params)
        desc = (fn.get("description") or "").strip().split("\n")[0][:110]
        out.append(f"{fn['name']}({sig})  -- {desc}")
    return "\n".join(out)


# Target-specific constraints. With a type fixed per prompt, a type whose every
# card fails leaves its GRPO group with zero advantage -- no gradient to learn the
# rule from -- so the rule has to be in the prompt. Each line is the failure that
# emptied that target at v4 step 1.
TARGET_HINTS = {
    "update_reservation_passengers": "Pass ALL passengers of the reservation (exactly _n_passengers entries), copying the unchanged ones and changing only what the customer asks.",
    "modify_pending_order_payment": "The new payment method must differ from the current one; a gift card may only be used if its balance in _gift_card_balances is at least the order's _order_total.",
    "modify_pending_order_items": "new_item_ids must be taken from that item's _swap_to_item_ids (same product, available); the customer names the option they want (e.g. color/size).",
    "exchange_delivered_order_items": "new_item_ids must be taken from that item's _swap_to_item_ids (same product, available); the customer names the option they want.",
    "update_reservation_flights": "New flights come from bookable_flights on the same route and must actually differ from the current ones; the customer names the flight or a rule that picks exactly one.",
}


def skeleton(domain, rec, target):
    """Precomputed valid slots for the target action, or None if these records
    cannot support it (the caller then resamples).

    At v4 step 1 the 4B synthesizer read the per-target rules and still swapped
    item_ids with new_item_ids, paid with a gift card below the order total, and
    added a passenger through update_reservation_passengers -- 16/16 of a group
    each time, so the group had zero advantage and RL could not learn the rule.
    Handing it the valid combinations keeps validity out of the search; writing
    the scenario and choosing among valid options -- the difficulty -- stays its job.
    """
    if domain == "retail":
        orders = rec["orders"]; user = rec["user"]
        pend = [o for o in orders if o.get("status") == "pending"]
        deliv = [o for o in orders if o.get("status") == "delivered"]
        pms = list((user.get("payment_methods") or {}).values())
        if target in ("modify_pending_order_items", "exchange_delivered_order_items"):
            pool = pend if target.startswith("modify") else deliv
            for o in pool:
                items = [{"item_id (keep this in item_ids)": i["item_id"], "name": i.get("name"),
                          "options": i.get("options"),
                          "new_item_ids must be one of": i.get("_swap_to_item_ids")}
                         for i in o.get("items", []) if i.get("_swap_to_item_ids")]
                if items:
                    return {"order_id": o["order_id"], "items": items,
                            "payment_method_id one of": [m["id"] for m in pms]}
            return None
        if target == "return_delivered_order_items":
            if not deliv: return None
            o = deliv[0]
            return {"order_id": o["order_id"], "item_ids from": [i["item_id"] for i in o["items"]],
                    "payment_method_id one of": [m["id"] for m in pms]}
        if target == "modify_pending_order_payment":
            for o in pend:
                cur = {p.get("payment_method_id") for p in o.get("payment_history", [])}
                ok = [m["id"] for m in pms if m["id"] not in cur and
                      (m.get("source") != "gift_card" or (m.get("balance") or 0) >= o["_order_total"])]
                if ok:
                    return {"order_id": o["order_id"], "order_total": o["_order_total"],
                            "current_payment": sorted(cur), "new payment_method_id one of": ok}
            return None
        if target in ("cancel_pending_order", "modify_pending_order_address"):
            if not pend: return None
            sk = {"order_id one of": [o["order_id"] for o in pend]}
            if target == "cancel_pending_order":
                sk["reason one of"] = ["no longer needed", "ordered by mistake"]
            else:
                sk["new address"] = "the customer states every field (address1, address2, city, state, country, zip) in known_info"
            return sk
        if target == "modify_user_address":
            return {"user_id": user["user_id"],
                    "new address": "the customer states every field in known_info"}
    if domain == "airline":
        res = rec["reservations"]
        if target == "update_reservation_passengers":
            r = res[0]
            return {"reservation_id": r["reservation_id"], "number of passengers (must stay)": len(r["passengers"]),
                    "current passengers": r["passengers"],
                    "rule": "pass exactly this many entries; change only fields the customer states"}
        if target == "update_reservation_flights":
            ok = [r for r in res if r.get("cabin") != "basic_economy"]
            if not ok or not rec.get("bookable_flights"): return None
            return {"reservation_id one of": [r["reservation_id"] for r in ok],
                    "new flights from": "bookable_flights (same route, different from current)"}
    return {}


def build(domain: str, seed: int, target: str | None = None) -> tuple[str, dict]:
    """Return (prompt, the records it was built from) for reproducibility.

    With `target`, the scenario must be resolved by that write action.
    """
    rng = random.Random(seed)
    db = _load_db(domain)
    for _ in range(40):                    # resample until the records support the target
        rec = SAMPLERS[domain](db, rng)
        if rec is None:
            raise RuntimeError(f"{domain}: no user with orders / reservations could be sampled")
        sk = skeleton(domain, rec, target) if target else {}
        if sk is not None:
            break
    else:
        sk = {}
    prompt = INSTRUCTION.format(domain=domain, tools=tool_list(domain), rules=RULES.get(domain, "- (none)"),
                                records=json.dumps(rec, ensure_ascii=False, indent=1))
    if target:
        prompt += (f"\n\nREQUIRED: the customer's goal must be resolved by calling `{target}` "
                   f"(it must appear in the action list). Pick the records that make "
                   f"`{target}` valid under the rules above.")
        if target in TARGET_HINTS:
            prompt += " " + TARGET_HINTS[target]
        if sk:
            prompt += ("\n\nVALID SLOTS for `" + target + "` (use exactly these ids; "
                       "anything else fails):\n" + json.dumps(sk, ensure_ascii=False, indent=1))
    return prompt, rec

